"""``prepare_purchase`` on the PUBLIC Orquestra MCP surface — falsified offline.

``https://mcp.geckovision.tech/orquestra/sse`` is unauthenticated: anyone on the internet
reaches these tools. So the thing this file pins hardest is not the happy path, it is the
BOUNDARY — the tool plans and verifies, and the caller signs:

1. A clean prepare hands back an UNSIGNED transaction and an ``exact`` binding, carrying
   the FRESH blockhash rather than the stale one the builder stamped.
2. A plan that pays the buyer back is refused BEFORE the builder is asked — proven by the
   fake builder's own call count, not by trusting the order the code reads in.
3. A failed receipt returns a refusal, a revert class, and NO transaction.
4. ``network`` is asserted or nothing happens: absent, ``unknown``, and off-vocabulary
   all refuse before any transport.
5. Neither module in the path may so much as NAME a signing or broadcast identifier.

Pattern B: every transport is an injected fake. No network, no key, no cent.
"""

