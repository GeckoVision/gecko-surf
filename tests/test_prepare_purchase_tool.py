@dataclass
class FakeBuilder:
    """Assembles a REAL legacy transaction from the plan it is handed, and counts calls.

    It mirrors the observed ``/build``: the accounts come from the plan (so a wrong
    derivation shows up in the bytes) and the blockhash is the builder's own stale one.
    ``calls`` is what makes "the refusal fired BEFORE the builder" falsifiable.
    """

    calls: list[dict[str, Any]] = field(default_factory=list)

    def __call__(self, plan: Any) -> BuiltTx:
        self.calls.append(dict(plan))
        from solders.hash import Hash
        from solders.instruction import AccountMeta, Instruction
        from solders.message import Message
        from solders.pubkey import Pubkey
        from solders.transaction import Transaction

        accounts = plan["accounts"]
        metas = [
            AccountMeta(
                pubkey=Pubkey.from_string(accounts[name]),
                is_signer=name == "signer",
                is_writable=name in WRITABLE,
            )
            for name in IDL_ORDER
        ]
        instruction = Instruction(
            program_id=Pubkey.from_string(PROGRAM),
            data=DISCRIMINATOR + b"\x00" * 8,
            accounts=metas,
        )
        message = Message.new_with_blockhash(
            [instruction],
            Pubkey.from_string(str(plan["feePayer"])),
            Hash.from_string(STALE_BLOCKHASH),
        )
        raw = bytes(Transaction.new_unsigned(message))
        return BuiltTx(tx=base64.b64encode(raw).decode(), encoding="base64")


@dataclass
class FakeRpc:
    """A replaying transport that records every method it was asked for."""

    err: Any | None = None
    units: int = 42_494
    calls: list[str] = field(default_factory=list)

    def __call__(self, url: str, method: str, params: list[Any]) -> dict[str, Any]:
        self.calls.append(method)
        if method == "getLatestBlockhash":
            return {
                "result": {
                    "value": {
                        "blockhash": FRESH_BLOCKHASH,
                        "lastValidBlockHeight": 371_004_211,
                    }
                }
            }
        if method == "simulateTransaction":
            return {
                "result": {
                    "context": {"slot": 371_004_061},
                    "value": {
                        "err": self.err,
                        "logs": [
                            "Program BUYuxRfhCMWavaUWxhGtPP3ksKEDZxCD5gzknk3JfAya invoke [1]",
                            "Program log: instruction: MakePurchase",
                        ],
                        "unitsConsumed": self.units,
                    },
                }
            }
        raise AssertionError(f"unexpected RPC method {method}")


#: "the key was not supplied at all", which is a different case from a supplied ``None``.
_ABSENT = object()


def _prepare(
    builder: FakeBuilder | None = None,
    rpc: FakeRpc | None = None,
    _drop_network: bool = False,
    **overrides: Any,
) -> dict[str, Any]:
    args: dict[str, Any] = {
        "store": "jonasbar",
        "product": "Water",
        "buyer": BUYER,
        "network": "mainnet",
        "rpc_url": RPC_URL,
        "table": 11,
    }
    args.update(overrides)
    if _drop_network:
        args.pop("network")
    return prepare_purchase_result(
        args,
        build_call=builder or FakeBuilder(),
        rpc_call=rpc or FakeRpc(),
    )


def _blockhash_of(transaction_base64: str) -> str:
    from solders.transaction import VersionedTransaction

    raw = base64.b64decode(transaction_base64)
    return str(VersionedTransaction.from_bytes(raw).message.recent_blockhash)


# --- 1. the clean path ----------------------------------------------------------


def test_a_clean_prepare_returns_an_unsigned_transaction_bound_exactly() -> None:
    builder, rpc = FakeBuilder(), FakeRpc()
    out = _prepare(builder, rpc)

    assert out["refused"] is False
    assert out["status"] == "pass"
    assert out["units_consumed"] == 42_494
    assert out["binding_strength"] == "exact"
    assert isinstance(out["binding"], str) and len(out["binding"]) == 64
    assert out["network"] == "mainnet"

    transaction = out["transaction"]
    assert transaction["signed"] is False
    assert transaction["encoding"] == "base64"
    # The bytes carry the node's FRESH blockhash, not the stale one the builder stamped.
    assert _blockhash_of(transaction["unsigned_transaction"]) == FRESH_BLOCKHASH
    assert out["expires"]["blockhash"] == FRESH_BLOCKHASH
    assert out["expires"]["last_valid_block_height"] == 371_004_211

    # The plan was DERIVED locally and matches addresses pinned outside this code path.
    plan = {entry["account"]: entry for entry in out["accounts"]}
    assert plan["receipts"]["address"] == JONASBAR_RECEIPTS
    assert plan["sender_token_account"]["address"] == BUYER_ATA
    assert plan["recipient_token_account"]["address"] == STORE_TOKEN
    assert plan["signer"]["address"] == BUYER
    # every account says what it IS in this instruction
    assert plan["authority"]["writable"] is True
    assert plan["authority"]["signer"] is False
    assert plan["signer"]["signer"] is True
    assert all(entry["role"] for entry in out["accounts"])

    assert builder.calls and builder.calls[0]["accounts"]["signer"] == BUYER
    assert rpc.calls == ["getLatestBlockhash", "simulateTransaction"]


def test_the_result_carries_no_payloads_and_nothing_is_persisted() -> None:
    # Invariant #1: a receipt's metadata, never the node's response body.
    out = _prepare()
    banned = {"logs", "logs_tail", "err", "headers", "authorization", "response"}
    assert not banned & set(out)
    assert "logs" not in str(out).lower()


# --- 2. the refusal that must beat the builder ----------------------------------


def test_a_self_paying_purchase_is_refused_before_the_builder_is_asked() -> None:
    # The buyer IS the store's authority, so ATA(signer) and ATA(authority) collapse to
    # one address and the purchase would pay the buyer back. Observed live: /build
    # answered HTTP 200 to exactly this.
    builder, rpc = FakeBuilder(), FakeRpc()
    out = _prepare(builder, rpc, buyer=STORE_AUTHORITY)

    assert out["refused"] is True
    assert out["code"] == "plan-refused"
    assert "same-token-account" in out["reason"]
    assert "transaction" not in out
    assert builder.calls == [], "the plan reached the builder"
    assert rpc.calls == [], "the plan reached the network"


