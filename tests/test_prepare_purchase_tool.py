# --- 4. the network is asserted, never inferred ---------------------------------


def test_a_missing_or_unknown_network_refuses_before_any_transport() -> None:
    # `unknown` is a legal answer and it refuses; a URL is not a network, because a fork
    # proxy answers at any hostname.
    for network in (_ABSENT, None, "unknown", "https://api.mainnet-beta.solana.com", 7):
        builder, rpc = FakeBuilder(), FakeRpc()
        overrides: dict[str, Any] = {} if network is _ABSENT else {"network": network}
        out = _prepare(builder, rpc, _drop_network=network is _ABSENT, **overrides)
        assert out["refused"] is True, network
        assert out["code"] == "network-not-asserted", network
        assert "transaction" not in out
        assert builder.calls == [] and rpc.calls == []


