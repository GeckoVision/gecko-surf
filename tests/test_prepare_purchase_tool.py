# --- 5. the boundary, asserted on the source itself -----------------------------


def _code_identifiers(path: Path) -> set[str]:
    """Every identifier the module's CODE uses. Docstrings and comments are ignored —
    they legitimately say "never signs"; only executable references count."""
    tree = ast.parse(path.read_text())
    identifiers: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name):
            identifiers.add(node.id)
        elif isinstance(node, ast.Attribute):
            identifiers.add(node.attr)
        elif isinstance(node, ast.alias):
            identifiers.add(node.name.rsplit(".", 1)[-1])
            if node.asname:
                identifiers.add(node.asname)
    return identifiers


def test_no_signing_or_broadcast_identifier_exists_in_the_public_tool() -> None:
    root = Path(__file__).resolve().parent.parent
    sources = [
        root / "gecko" / "prepare_purchase.py",
        root / "gecko" / "providers" / "catalog_surface.py",
    ]
    forbidden = {
        "TransactionSigner",
        "SigningBackend",
        "Keypair",
        "sign_and_send",
        "sendTransaction",
        "send_transaction",
        "sign",
        "sign_transaction",
        "sign_message",
        "partial_sign",
        "new_signed",
        "secret_key",
        "from_seed",
        "broadcast",
    }
    for path in sources:
        leaked = forbidden & _code_identifiers(path)
        assert not leaked, f"{path.name} must not reference {sorted(leaked)} in code"


def test_the_tool_persists_nothing() -> None:
    root = Path(__file__).resolve().parent.parent / "gecko" / "prepare_purchase.py"
